#define KEYSVC_KEY_COUNT (sizeof keydefs / sizeof keydefs[0])

static inline unsigned keysvc_key_index(unsigned index)
{
	for (unsigned i = 0; i < index; i++)
		if (keydefs[i].plain == keydefs[index].plain)
			return i;
	return index;
}

static inline uint16_t keysvc_navigation_code(uint16_t code)
{
	switch (code) {
	case 0x7100: return 0xF300;
	case 0x7300: return 0xF200;
	case 0x7500: return 0xF400;
	case 0x7700: return 0xF100;
	default: return code;
	}
}

static inline uint16_t keysvc_key_code(unsigned index, uint8_t modifiers)
{
	const struct keydef *key = &keydefs[index];
	return keysvc_navigation_code(modifiers & MOD_CTRL ? key->ctrl :
		modifiers & MOD_SHIFT ? key->shifted : key->plain);
}
